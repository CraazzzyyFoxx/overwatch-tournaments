"""Native MV runtime behavior under independent reader and narrowly owning roles.

Main executes these real PostgreSQL cases; no legacy materialized view is an oracle.
"""

from __future__ import annotations

import asyncio
import importlib.util
from pathlib import Path
from uuid import uuid4

import pytest
import sqlalchemy as sa
from sqlalchemy.engine import make_url
from sqlalchemy.ext.asyncio import AsyncSession, create_async_engine

from shared.models.stats import mv_entity_global_stats
from src.services.hero_stats_refresh import _ADVISORY_LOCK_KEY, HeroStatsRefresher

_spec = importlib.util.spec_from_file_location(
    "mixstatsmv01_mv_runtime_revision",
    Path(__file__).resolve().parents[2] / "migrations/versions/mixstatsmv01_mv_tournament_only.py",
)
assert _spec is not None and _spec.loader is not None
_revision = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(_revision)
_MV = "stats.mv_entity_global_stats"


@pytest.fixture
def mv_roles(stats_parity_database):
    """Cluster roles are unique, non-superuser, and cleaned after their clone's tests."""
    url, ids = stats_parity_database
    engine = sa.create_engine(url)
    owner, reader = (f"p4_mv_{kind}_{uuid4().hex}" for kind in ("owner", "reader"))
    quote = engine.dialect.identifier_preparer.quote
    created = []
    original_owner = None
    try:
        with engine.begin() as conn:
            original_owner = conn.scalar(sa.text("SELECT current_user"))
            for role in (owner, reader):
                conn.execute(
                    sa.text(f"CREATE ROLE {quote(role)} NOLOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOINHERIT")
                )
                created.append(role)
            conn.execute(sa.text(f"GRANT USAGE ON SCHEMA stats TO {quote(reader)}"))
            conn.execute(sa.text(f"GRANT SELECT ON {_MV} TO {quote(reader)}"))
            conn.execute(
                sa.text(
                    f"GRANT USAGE ON SCHEMA stats, catalog, encounter, tournament, public, players TO {quote(owner)}"
                )
            )
            conn.execute(
                sa.text(
                    "GRANT SELECT ON stats.fact, stats.match, stats.stat_def, catalog.entity, "
                    "encounter.game, encounter.encounter, tournament.tournament, public.workspace_member, "
                    f'players."user" TO {quote(owner)}'
                )
            )
            conn.execute(sa.text(f"GRANT CREATE ON SCHEMA stats TO {quote(owner)}"))
            conn.execute(sa.text(f"ALTER MATERIALIZED VIEW {_MV} OWNER TO {quote(owner)}"))
            conn.execute(sa.text(f"REVOKE CREATE ON SCHEMA stats FROM {quote(owner)}"))
        yield url, ids, owner, reader
    finally:
        with engine.begin() as conn:
            if original_owner is not None:
                conn.execute(sa.text(f"ALTER MATERIALIZED VIEW {_MV} OWNER TO {quote(original_owner)}"))
            for role in created:
                conn.execute(sa.text(f"DROP OWNED BY {quote(role)}"))
                conn.execute(sa.text(f"DROP ROLE {quote(role)}"))
        engine.dispose()


async def _role(session, role):
    # Role names are generated by the fixture, never supplied by a request.
    await session.execute(sa.text(f'SET LOCAL ROLE "{role}"'))
    assert await session.scalar(sa.text("SELECT NOT rolsuper FROM pg_roles WHERE rolname=current_user"))


async def _rows(session):
    return (
        await session.execute(
            sa.select(mv_entity_global_stats).order_by(
                mv_entity_global_stats.c.discipline,
                mv_entity_global_stats.c.stat_id,
                mv_entity_global_stats.c.entity_id,
            )
        )
    ).all()


async def _assert_exact_derivation(session):
    # Compare both directions, including IEEE float bits, to a fresh native derivation.
    projection = "discipline,stat_id,entity_id,float8send(best_value),float8send(avg),metadata"
    expected = f"SELECT {projection} FROM ({_revision._TOURNAMENT_ONLY_SELECT}) expected"
    actual = f"SELECT {projection} FROM {_MV}"
    differences = await session.execute(
        sa.text(f"({expected} EXCEPT ALL {actual}) UNION ALL ({actual} EXCEPT ALL {expected})")
    )
    assert differences.all() == []


def test_ordinary_reader_has_no_native_source_or_refresh_privileges(mv_roles):
    asyncio.run(_ordinary_reader_has_no_native_source_or_refresh_privileges(mv_roles))


async def _ordinary_reader_has_no_native_source_or_refresh_privileges(mv_roles):
    url, _, _, reader = mv_roles
    engine = create_async_engine(make_url(url).set(drivername="postgresql+asyncpg"))
    try:
        async with AsyncSession(engine) as session:
            await _role(session, reader)
            assert await _rows(session)
            assert not await session.scalar(sa.text("SELECT has_table_privilege(current_user,'stats.fact','SELECT')"))
            with pytest.raises(sa.exc.DBAPIError):
                await HeroStatsRefresher().refresh(session)
            await session.rollback()
    finally:
        await engine.dispose()


def test_unpopulated_view_errors_then_owner_populates_without_legacy(mv_roles):
    asyncio.run(_unpopulated_view_errors_then_owner_populates_without_legacy(mv_roles))


async def _unpopulated_view_errors_then_owner_populates_without_legacy(mv_roles):
    url, _, owner, reader = mv_roles
    engine = create_async_engine(make_url(url).set(drivername="postgresql+asyncpg"))
    try:
        async with AsyncSession(engine) as session:
            await session.execute(sa.text(f"REFRESH MATERIALIZED VIEW {_MV} WITH NO DATA"))
            await session.commit()
            await _role(session, reader)
            with pytest.raises(sa.exc.DBAPIError) as error:
                await _rows(session)
            assert error.value.orig.sqlstate == "55000"
            await session.rollback()
            await _role(session, owner)
            assert await HeroStatsRefresher().refresh(session)
            await _role(session, owner)
            await _assert_exact_derivation(session)
            await session.rollback()
            await _role(session, reader)
            assert await _rows(session)
    finally:
        await engine.dispose()


def test_native_refresh_is_concurrent_and_advisory_locked(mv_roles):
    asyncio.run(_native_refresh_is_concurrent_and_advisory_locked(mv_roles))


async def _native_refresh_is_concurrent_and_advisory_locked(mv_roles):
    url, ids, owner, reader = mv_roles
    engine = create_async_engine(make_url(url).set(drivername="postgresql+asyncpg"))
    try:
        async with AsyncSession(engine) as admin:
            assert await admin.scalar(sa.text(f"SELECT relispopulated FROM pg_class WHERE oid='{_MV}'::regclass"))
            dependencies = (
                (
                    await admin.execute(
                        sa.text(
                            "SELECT DISTINCT n.nspname FROM pg_rewrite r JOIN pg_depend d ON d.objid=r.oid "
                            "AND d.classid='pg_rewrite'::regclass AND d.refclassid='pg_class'::regclass "
                            "JOIN pg_class c ON c.oid=d.refobjid JOIN pg_namespace n ON n.oid=c.relnamespace "
                            f"WHERE r.ev_class='{_MV}'::regclass"
                        )
                    )
                )
                .scalars()
                .all()
            )
            assert "stats" in dependencies
            assert not {"matches", "log_processing"}.intersection(dependencies)
            await admin.execute(
                sa.text(
                    "UPDATE stats.fact SET value=value+10000 WHERE match_id=:match AND workspace_member_id=:member "
                    "AND segment=0 AND entity_id=:hero AND stat_id=(SELECT id FROM stats.stat_def "
                    "WHERE discipline='overwatch' AND code='eliminations')"
                ),
                ids,
            )
            await admin.commit()
        async with AsyncSession(engine) as held, AsyncSession(engine) as refreshing:
            await _role(held, reader)
            before = await _rows(held)
            await held.execute(sa.text(f"SELECT pg_advisory_xact_lock({_ADVISORY_LOCK_KEY})"))
            await _role(refreshing, owner)
            assert await HeroStatsRefresher().refresh(refreshing) is False
            assert await _rows(held) == before
            await refreshing.rollback()
            await held.rollback()
            # Retain the reader's AccessShareLock: plain REFRESH would block here.
            await _role(held, reader)
            assert await _rows(held) == before
            await _role(refreshing, owner)
            assert await asyncio.wait_for(HeroStatsRefresher().refresh(refreshing), timeout=15)
            assert await _rows(held) != before
            await held.rollback()
            await _role(refreshing, owner)
            owned = (
                (
                    await refreshing.execute(
                        sa.text(
                            "SELECT c.relname FROM pg_class c JOIN pg_roles r ON r.oid=c.relowner "
                            "WHERE r.rolname=current_user AND c.relkind IN ('r','m','v','S')"
                        )
                    )
                )
                .scalars()
                .all()
            )
            assert owned == ["mv_entity_global_stats"]
            await _assert_exact_derivation(refreshing)
    finally:
        await engine.dispose()
